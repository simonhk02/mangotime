function leapMonth(y: number) { return LUNAR_INFO[y - 1900] & 0xf; }
function leapDays(y: number) { return leapMonth(y) ? ((LUNAR_INFO[y - 1900] & 0x10000) ? 30 : 29) : 0; }
function monthDays(y: number, m: number) { return (LUNAR_INFO[y - 1900] & (0x10000 >> m)) ? 30 : 29; }
function yearDays(y: number) {
  let sum = 348;
  for (let i = 0x8000; i > 0x8; i >>= 1) sum += (LUNAR_INFO[y - 1900] & i) ? 1 : 0;
  return sum + leapDays(y);
}

const BASE = Date.UTC(1900, 0, 31); // 1900-01-31 = 農曆正月初一

/** 新曆 Date → 農曆簡短顯示（初一/初二…；初一嗰日顯示月份，例如「十月」） */
export function lunarShort(date: Date): string {
  const offset = Math.floor((Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) - BASE) / 86400000);
  if (offset < 0 || offset > 80000) return "";
  let remaining = offset;
  let year = 1900;
  while (year < 2101) {
    const yd = yearDays(year);
    if (remaining < yd) break;
    remaining -= yd;
    year++;
  }
  const leap = leapMonth(year);
  let month = 1;
  let isLeap = false;
  let daysInMonth = 0;
  while (month <= 12) {
    if (leap && month === leap + 1 && !isLeap) {
      // 閏月
      isLeap = true;
      daysInMonth = leapDays(year);
      month--;
    } else {
      daysInMonth = monthDays(year, month);
    }
    if (remaining < daysInMonth) break;
    remaining -= daysInMonth;
    if (isLeap && month === leap) isLeap = false;
    month++;
  }
  const day = remaining + 1;
  if (day === 1) return (isLeap ? "閏" : "") + LUNAR_MONTHS[month - 1];
  return LUNAR_DAYS[day - 1];
}
